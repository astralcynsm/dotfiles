#!/usr/bin/env bash
# ============================================================
#  手动切换明暗（快捷键入口，建议绑 SUPER + D）
#
#  极薄的转发层：真正的切换与「手动优先」时间戳都在 switch.sh 的
#  toggle_mode() 里落 —— 三条手动入口（快捷键 / ii 界面 / 命令行）
#  共用那一处记录，这里不再自己写，免得两边逻辑漂移。
#
#  例：白天你手动切到 dark 想看点深色的，自动逻辑会忍住不动，
#      到日落之后的那个周期才重新接管；反过来熬夜时手动切 light 同理。
# ============================================================

set -uo pipefail

exec "$HOME/.config/theme-switcher/switch.sh" --toggle-mode
